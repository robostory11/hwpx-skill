def 홍보문_찾기():
    """되살아난 홍보·유도 문구를 찾는다."""
    걸린것 = []
    for 이름 in 홍보검사대상:
        길 = 뿌리 / 이름
        if not 길.exists():
            걸린것.append((이름, 0, '파일이 없다', '검사 대상 파일이 사라졌다'))
            continue
        for 번호, 줄 in enumerate(길.read_text(encoding='utf-8').splitlines(), 1):
            if 면제표식 in 줄:
                continue
            for 무늬, 설명 in 홍보패턴:
                if re.search(무늬, 줄, re.IGNORECASE):
                    걸린것.append((이름, 번호, 설명, 줄.strip()[:90]))
                    break
    return 걸린것


def 우리것_확인():
    """우리가 넣은 것이 살아 있는지 본다."""
    잃은것 = []
    for 자산 in 우리자산:
        길 = 뿌리 / 자산['파일']
        if not 길.exists():
            잃은것.append((자산['파일'], '파일이 통째로 사라졌다', 자산['무엇']))
            continue
        글 = 길.read_text(encoding='utf-8', errors='replace')
        for 표식, 왜 in 자산['있어야 하는 것']:
            if 표식 not in 글:
                잃은것.append((자산['파일'], f'"{표식}"이 없다', 왜))
    return 잃은것


def 알림(말):
    print(말)


def main():
    조용히 = '--조용히' in sys.argv or '--quiet' in sys.argv

    try:
        홍보 = 홍보문_찾기()
        잃음 = 우리것_확인()
    except Exception as 오류:  # 검사 자체가 깨진 경우 — 판정과 구별해야 한다
        print('!! 포크 문지기가 검사를 마치지 못했습니다: %s' % 오류)
        print('   이것은 "문제 없음"이 아닙니다. 스크립트를 고쳐 다시 돌리십시오.')
        return 2

    문제수 = len(홍보) + len(잃음)

    if 문제수 == 0:
        if not 조용히:
            알림('포크 문지기: 통과 — 홍보 문구 없음, 우리가 넣은 것 모두 살아 있음')
        return 0

    # 실패는 시끄럽게. 조용히 옵션이어도 문제가 있으면 반드시 말한다.
    알림('')
    알림('=' * 68)
    알림('  포크 문지기: 문제 %d건 — 업스트림 병합이 우리 것을 덮었습니다' % 문제수)
    알림('=' * 68)

    if 홍보:
        알림('')
        알림('[1] 되살아난 홍보·유도 문구 %d건 — 걷어내야 합니다' % len(홍보))
        알림('    이 문구가 남아 있으면 문서를 만들 때마다 사장님 대화에 남의 저장소 홍보가 나갑니다.')
        for 이름, 번호, 설명, 줄 in 홍보:
            알림('    · %s:%d  (%s)' % (이름, 번호, 설명))
            알림('      %s' % 줄)
        알림('    → 그 줄을 지우십시오. 설명을 위해 인용해야 한다면 같은 줄에')
        알림('      %s 표식을 달면 이 검사에서 면제됩니다.' % 면제표식)

    if 잃음:
        알림('')
        알림('[2] 사라진 우리 자산 %d건 — 되살려야 합니다' % len(잃음))
        for 파일, 무엇, 왜 in 잃음:
            알림('    · %s — %s' % (파일, 무엇))
            알림('      %s' % 왜)
        알림('    → git log로 우리 커밋을 찾아 그 부분을 다시 넣으십시오.')
        알림('      우리 커밋: diff_hwpx.py 신설 · 무음 실패 일곱 건 수정 · 쪽 설정 층 확장')

    알림('')
    return 1


if __name__ == '__main__':
    sys.exit(main())
