"""포크 문지기 — 업스트림에서 받아온 뒤 우리 것이 덮이지 않았는지 기계가 확인한다.

왜 필요한가:
  이 저장소는 jkf87/hwpx-skill의 포크(robostory11/hwpx-skill)다. 업스트림에서 새 기능을
  받아오는 것은 이득이지만, 병합할 때 두 가지가 조용히 망가진다.

    1) 원저작자의 별점 요청 문구가 되살아난다.
       2026-07-29에 실제로 사장님 대화에 "Star를 눌러주시면 큰 힘이 됩니다"가 나갔다.
       SKILL.md가 "결과물을 전달한 뒤 이 한 줄을 덧붙인다"고 지시하고 있었기 때문이다.
       우리 포크에서 남의 저장소를 홍보할 이유가 없다.

    2) 우리가 넣은 것이 덮인다.
       diff_hwpx.py(두 한글 파일 6층 대조)는 원본에 없는 우리 도구다. 계약서 발송본을
       사장님이 손으로 고치신 것을 되찾으려고 만들었고, 무음 실패 일곱 건을 교차검증으로
       고친 이력이 있다. 병합 충돌로 되돌아가면 그 수정이 통째로 사라진다.

  "병합한 뒤 확인하자"를 사람 기억에 맡기면 반드시 잊는다. 그래서 검사를 코드로 두고
  .githooks/post-merge가 병합 직후 자동으로 부른다.

쓰는 법:
  python scripts/fork_guard.py            # 검사만
  python scripts/fork_guard.py --조용히   # 통과하면 아무 말 안 함 (훅에서 사용)

  되돌아오는 값:  0 통과 / 1 문제 발견 / 2 검사 자체가 깨짐
  ※ 오류와 판정을 다른 값으로 가른다. 같은 값을 쓰면 검사가 죽은 것을
     "문제 없음"이나 "문제 있음"으로 잘못 읽는다 (diff_hwpx.py에서 겪은 함정).

새 자산을 넣었을 때:
  아래 우리자산 목록에 한 줄 더한다. 목록에 없으면 이 문지기가 지켜주지 않는다.

훅 설치 (환경을 새로 만들 때 한 번):
  git config core.hooksPath .githooks
"""
